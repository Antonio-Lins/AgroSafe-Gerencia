CREATE TABLE usuarios (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nome VARCHAR(150) NOT NULL,
                          email VARCHAR(150) NOT NULL UNIQUE,
                          senha_hash VARCHAR(100) NOT NULL,
                          perfil VARCHAR(20) NOT NULL
);

CREATE TABLE talhoes (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         codigo VARCHAR(50) NOT NULL UNIQUE,
                         hectares NUMERIC(12,2) NOT NULL,
                         cultura VARCHAR(100) NOT NULL,
                         data_liberacao DATE
);

CREATE TABLE defensivos (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nome_comercial VARCHAR(150) NOT NULL,
                            principio_ativo VARCHAR(150) NOT NULL,
                            dias_carencia INTEGER NOT NULL
);

CREATE TABLE aplicacoes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            talhao_id BIGINT NOT NULL,
                            defensivo_id BIGINT NOT NULL,
                            usuario_id BIGINT NOT NULL,
                            data_aplicacao DATE NOT NULL,
                            data_liberacao_calculada DATE NOT NULL,
                            cancelada BOOLEAN NOT NULL DEFAULT FALSE,
                            motivo_cancelamento VARCHAR(500),
                            cancelada_por_id BIGINT,
                            cancelada_em TIMESTAMP(6),

                            CONSTRAINT fk_aplicacoes_talhao
                                FOREIGN KEY (talhao_id) REFERENCES talhoes(id),

                            CONSTRAINT fk_aplicacoes_defensivo
                                FOREIGN KEY (defensivo_id) REFERENCES defensivos(id),

                            CONSTRAINT fk_aplicacoes_usuario
                                FOREIGN KEY (usuario_id) REFERENCES usuarios(id),

                            CONSTRAINT fk_aplicacoes_cancelada_por
                                FOREIGN KEY (cancelada_por_id) REFERENCES usuarios(id)
);